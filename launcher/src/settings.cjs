const net = require('node:net');
const path = require('node:path');
const { parse } = require('dotenv');
const { readFileSync } = require('node:fs');

const APP_DEFAULTS = {
  clockit: { name: 'ClockIt', frontendPort: 2400 },
};

function defaultsFor(appKind) {
  const app = APP_DEFAULTS[appKind];
  if (!app) {
    throw new Error(`Unknown launcher application: ${appKind}`);
  }
  return {
    appName: app.name,
    apiScheme: 'http',
    apiHost: '127.0.0.1',
    apiPort: 4002,
    frontendHost: '127.0.0.1',
    frontendPort: app.frontendPort,
  };
}

function parsePort(value, label) {
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`${label} must be a whole number from 1 to 65535.`);
  }
  return port;
}

function hostForUrl(host) {
  const trimmed = String(host ?? '').trim();
  if (!trimmed || /[\s/@?#]/.test(trimmed)) {
    throw new Error('StoreIt host must be a hostname or IP address without a URL path.');
  }
  const unwrapped = trimmed.startsWith('[') && trimmed.endsWith(']')
    ? trimmed.slice(1, -1)
    : trimmed;
  return unwrapped.includes(':') ? `[${unwrapped}]` : unwrapped;
}

function validateSettings(input, appKind) {
  const defaults = defaultsFor(appKind);
  const apiScheme = input.apiScheme === 'https' ? 'https' : input.apiScheme === 'http' ? 'http' : '';
  if (!apiScheme) {
    throw new Error('StoreIt connection must use HTTP or HTTPS.');
  }

  const apiPort = parsePort(input.apiPort, 'StoreIt API port');
  const frontendPort = parsePort(input.frontendPort, `${defaults.appName} web port`);
  const apiUrl = new URL(`${apiScheme}://${hostForUrl(input.apiHost)}:${apiPort}/`);
  if (apiUrl.username || apiUrl.password) {
    throw new Error('StoreIt host must not contain credentials.');
  }

  const frontendHost = String(input.frontendHost ?? '').trim();
  if (
    !frontendHost ||
    (frontendHost !== 'localhost' && frontendHost !== '0.0.0.0' && net.isIP(frontendHost) === 0)
  ) {
    throw new Error('Web listen address must be localhost, 0.0.0.0, or a valid IP address.');
  }

  return {
    appName: defaults.appName,
    apiScheme,
    apiHost: apiUrl.hostname,
    apiPort,
    apiUrl: `${apiUrl.origin}`,
    frontendHost,
    frontendPort,
  };
}

function quoteEnvValue(value) {
  return `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '')}"`;
}

function serializeSettings(settings) {
  return [
    '# Generated by the desktop launcher. Edit settings in the launcher instead.',
    `STOREIT_API_URL=${quoteEnvValue(settings.apiUrl)}`,
    `FRONTEND_HOST=${quoteEnvValue(settings.frontendHost)}`,
    `FRONTEND_PORT=${settings.frontendPort}`,
    '',
  ].join('\n');
}

function settingsFromEnvFile(envPath, appKind) {
  const defaults = defaultsFor(appKind);
  let values = {};
  try {
    values = parse(readFileSync(envPath));
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw new Error(`Could not read launcher settings: ${error.message}`);
    }
  }

  const storedApiUrl = values.STOREIT_API_URL;
  let apiScheme = defaults.apiScheme;
  let apiHost = defaults.apiHost;
  let apiPort = defaults.apiPort;
  if (storedApiUrl) {
    let url;
    try {
      url = new URL(storedApiUrl);
    } catch {
      throw new Error('Saved StoreIt API URL is invalid. Update it in Settings.');
    }
    if (!['http:', 'https:'].includes(url.protocol) || url.pathname !== '/' || url.search || url.hash) {
      throw new Error('Saved StoreIt API URL must be an HTTP(S) origin. Update it in Settings.');
    }
    apiScheme = url.protocol.slice(0, -1);
    apiHost = url.hostname;
    apiPort = url.port || (apiScheme === 'https' ? 443 : 80);
  }

  return validateSettings({
    apiScheme,
    apiHost,
    apiPort,
    frontendHost: values.FRONTEND_HOST ?? defaults.frontendHost,
    frontendPort: values.FRONTEND_PORT ?? defaults.frontendPort,
  }, appKind);
}

function settingsFileFor(userDataDirectory) {
  return path.join(userDataDirectory, '.env');
}

function browserUrl(settings) {
  const host = settings.frontendHost === '0.0.0.0' || settings.frontendHost === '::'
    ? '127.0.0.1'
    : settings.frontendHost === '::1'
      ? '[::1]'
      : settings.frontendHost;
  return `http://${host}:${settings.frontendPort}/`;
}

module.exports = {
  APP_DEFAULTS,
  browserUrl,
  defaultsFor,
  serializeSettings,
  settingsFileFor,
  settingsFromEnvFile,
  validateSettings,
};
